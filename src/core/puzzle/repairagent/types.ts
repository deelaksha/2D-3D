/**
 * AI-Assisted Repair Agent Domain Types (Phase 73).
 *
 * CRITICAL ARCHITECTURAL CONSTRAINTS:
 *  - The repair agent may ONLY modify approved parametric variables.
 *  - Arbitrary mesh vertices or uncontrolled CAD geometry must NEVER be modified directly.
 *  - Bounded by maximum iterations, maximum parameter changes, and minimum improvement threshold.
 *  - Loop prevention with cycle detection.
 *  - Complete, auditable iteration history returned for every repair session.
 */

import type { ID } from "@/core/model/types";
import type { ParametricDesignSpecification } from "../ailayer/types";
import type { CanonicalPuzzle } from "../canonical/types";
import type { AIValidationPasses } from "../designgeneration/types";
import type { CritiqueIssue, DesignCritique } from "../critic/types";

/**
 * Whitelist of approved parametric variables the repair agent is permitted to adjust.
 */
export type ApprovedParametricVariable =
  | "tab_width"             // Contact tab width on interfaces
  | "slot_width"            // Receiver slot width on interfaces
  | "clearance"             // Laser cut kerf clearance tolerance
  | "interface_position"    // Normalized edge offset position (0.0 to 1.0)
  | "angle_range"           // Preferred joining angle nominal/min/max
  | "piece_dimension"       // Bounding width, height, or depth
  | "connection_density"    // Piece count or interconnected joint count
  | "stock_dimension";      // Cardboard sheet stock dimensions for nesting

/**
 * Explicit modification proposal targeting an approved parametric variable.
 */
export interface ParametricModificationProposal {
  proposalId: string;
  variable: ApprovedParametricVariable;
  parameterPath: string; // e.g. "connection_preferences.clearance", "overall_size.widthMm"
  oldValue: number | string | boolean;
  newValue: number | string | boolean;
  rationale: string;
  targetIssueId: string;
  affectedEntityId: ID;
}

/**
 * Log of a single repair loop iteration.
 */
export interface RepairIterationLog {
  iterationNumber: number;

  /** Identified problems from deterministic validation or AI critic */
  identifiedProblems: CritiqueIssue[];

  /** Whitelisted parameters selected for adjustment */
  selectedParameters: ApprovedParametricVariable[];

  /** Structured proposals generated by the repair agent */
  proposedModifications: ParametricModificationProposal[];

  /** Validated modifications applied to the specification */
  appliedModifications: ParametricModificationProposal[];

  /** The regenerated specification after applying modifications */
  regeneratedSpecification: ParametricDesignSpecification;

  /** 5-gate deterministic validation results for this iteration */
  validationPasses: AIValidationPasses;

  /** Design critique for this iteration */
  critique: DesignCritique;

  /** Quality score progression */
  qualityScoreBefore: number;
  qualityScoreAfter: number;
  scoreImprovement: number;

  /** State hash of the parameter vector to detect cycles */
  stateHash: string;

  /** Iteration wall-clock duration */
  durationMs: number;
}

/**
 * Configuration options for the AI Repair Agent.
 */
export interface RepairAgentConfig {
  /** Maximum closed-loop repair iterations (default: 5) */
  maxIterations?: number;

  /** Maximum parameter changes allowed per iteration (default: 3) */
  maxParameterChangesPerIteration?: number;

  /** Minimum quality score increase required to continue iterations (default: 1.5) */
  minImprovementThreshold?: number;

  /** Target composite quality score considered fully satisfactory (default: 85.0) */
  targetQualityScore?: number;
}

/**
 * Final resolution status of a repair session.
 */
export type RepairSessionStatus =
  | "CONVERGED_PASS"              // All validation gates passed & critique rated PASS
  | "MAX_ITERATIONS_REACHED"      // Hit iteration ceiling before full convergence
  | "MIN_IMPROVEMENT_NOT_MET"     // Terminated early due to quality plateau
  | "CYCLE_DETECTED"              // Loop prevention triggered by recurring parameter state
  | "FAILED_UNREPAIRABLE";        // Hard failures persisted that could not be resolved parametrically

/**
 * Complete result of a repair session including full iteration history.
 */
export interface RepairSessionResult {
  sessionId: string;
  status: RepairSessionStatus;
  initialSpecification: ParametricDesignSpecification;
  finalSpecification: ParametricDesignSpecification;
  finalCanonicalPuzzle?: CanonicalPuzzle;
  initialCritique: DesignCritique;
  finalCritique: DesignCritique;
  iterations: RepairIterationLog[];
  totalIterations: number;
  totalParameterChanges: number;
  overallScoreImprovement: number;
  totalDurationMs: number;
  summary: string;
}
